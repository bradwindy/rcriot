function paint(rows: string[]): HTMLCanvasElement {
  const canvas = document.createElement('canvas');
  canvas.width = SIZE;
  canvas.height = SIZE;
  canvas.style.imageRendering = 'pixelated';
  const ctx = canvas.getContext('2d');
  if (!ctx) return canvas;
  const filled = (x: number, y: number): boolean => (rows[y - PAD]?.[x - PAD] ?? '.') !== '.';
  const nextToFilled = (x: number, y: number): boolean => {
    for (let dy = -1; dy <= 1; dy++) for (let dx = -1; dx <= 1; dx++) if (filled(x + dx, y + dy)) return true;
    return false;
  };
  for (let y = 0; y < SIZE; y++) {
    for (let x = 0; x < SIZE; x++) {
      if (filled(x, y)) ctx.fillStyle = COLORS[rows[y - PAD][x - PAD]];
      else if (nextToFilled(x, y)) ctx.fillStyle = COLORS.K;
      else continue;
      ctx.fillRect(x, y, 1, 1);
    }
  }
  return canvas;
}

const icons = new Map<ItemKind, HTMLCanvasElement>();

/** The 24x24 icon for a pick-up. The canvas is shared per kind, so use drawImage rather than inserting it twice. */
export function itemIcon(kind: ItemKind): HTMLCanvasElement {
  let icon = icons.get(kind);
  if (!icon) {
    icon = paint(ART[kind]);
    icons.set(kind, icon);
  }
  return icon;
}
